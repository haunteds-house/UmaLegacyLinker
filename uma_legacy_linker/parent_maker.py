class ParentMakerError(RuntimeError):
    pass


SUPPORTED_FACTOR_TYPES = (
    "white_skill",
    "scenario",
    "red_aptitude",
    "blue_stat",
    "unique",
    "white_race",
)

FACTOR_TYPE_LABELS = {
    "white_skill": "White skill",
    "scenario": "Scenario",
    "red_aptitude": "Pink aptitude",
    "blue_stat": "Blue stat",
    "unique": "Green unique",
    "white_race": "Race spark",
}

# These scenario factors grant the same skill hint within each family. The
# performance-dependent +/non-+ factor generated by the new trainee is a
# separate end-of-career outcome, so Parent Maker deliberately treats the two
# source variants as equivalent while producing intermediate parents.
_SCENARIO_EQUIVALENCE_BASES = {
    "ignited spirit: wit",
    "racing spirit: stamina",
}


@dataclass(frozen=True)
class SparkTarget:
    factor_type: str
    name: str
    priority: float = 1.0
    preferred_stars: int = 1
    equivalents: tuple[str, ...] = ()

    def normalized(self) -> "SparkTarget":
        factor_type = str(self.factor_type or "").strip()
        if factor_type not in SUPPORTED_FACTOR_TYPES:
            raise ParentMakerError(f"Unsupported factor type: {factor_type or '(empty)'}")
        name = str(self.name or "").strip()
        if not name:
            raise ParentMakerError("Every Parent Maker target needs a factor name.")
        equivalents = tuple(
            dict.fromkeys(
                value.strip()
                for value in (str(item or "") for item in self.equivalents)
                if value.strip()
            )
        )
        return SparkTarget(
            factor_type=factor_type,
            name=name,
            priority=max(0.0, float(self.priority)),
            preferred_stars=max(1, min(9, int(self.preferred_stars))),
            equivalents=equivalents,
        )


