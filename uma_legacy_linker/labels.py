def display_text(text: Any, language: str = "en") -> Any:
    """Preserve API compatibility for presentation helpers; text is English."""
    return text


def scoring_label(key: str, language: str = "en") -> str:
    return SCORING_LABELS.get(str(key), str(key))


def profile_values(kind: str, language: str = "en") -> tuple[str, ...]:
    return tuple(PROFILE_OPTIONS[kind].values())


def profile_label(kind: str, code: str, language: str = "en") -> str:
    options = PROFILE_OPTIONS[kind]
    return options.get(code, next(iter(options.values())))


def profile_code(kind: str, display_or_code: str) -> str:
    options = PROFILE_OPTIONS[kind]
    if display_or_code in options:
        return display_or_code
    return next((code for code, label in options.items() if label == display_or_code), next(iter(options)))
